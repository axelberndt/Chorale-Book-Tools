package keySignatures;

/**
 * An enumeration of key modes.
 * @author Axel Berndt
 */
public enum KeyMode {
    major,          // Major mode.
    minor,          // Minor mode.
    dorian,         // Dorian mode (the first mode).
    hypodorian,     // Hypodorian mode (the second mode).
    phrygian,       // Phrygian mode (the third mode).
    hypophrygian,   // Hypophrygian mode (the fourth mode).
    lydian,         // Lydian mode (the fifth mode).
    hypolydian,     // Hypolydian mode  (the sixth mode).
    mixolydian,     // Mixolydian mode (the seventh mode).
    hypomixolydian, // Hypomixolydian mode (the eighth mode).
    peregrinus,     // Tonus peregrinus (the ninth mode).
    ionian,         // Ionian mode.
    hypoionian,     // Hypoionian mode.
    aeolian,        // Aeolian mode.
    hypoaeolian,    // Hypoaeolian mode.
    locrian,        // Locrian mode.
    hypolocrian     // Hypolocrian mode.
}
